/**
 * يبني الـ system prompt كامل مع الذكريات
 * @param {string} personality - اسم الشخصية
 * @param {string} gender - جنس المستخدم
 * @param {Array}  memories - الذكريات المحفوظة (اختياري)
 * @returns {string} - الـ system prompt كامل
 */
export function getPersonalityPrompt(personality, gender = "ولد", memories = []) {
  const fn = PERSONALITIES[personality];
  const basePrompt = typeof fn === "function"
    ? fn(gender)
    : PERSONALITIES["blak"](gender);

  if (memories && memories.length > 0) {
    const memoriesText = memories
      .map((m) => `- ${m.content}`)
      .join("\n");

    return `${basePrompt}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
🧠 ذكريات محفوظة عن المستخدم:
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
${memoriesText}

استخدم هذه المعلومات بشكل طبيعي في ردودك دون الإشارة إليها صراحةً.
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━`;
  }

  return basePrompt;
}


